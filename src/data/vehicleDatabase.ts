// ─── Yardımcı fonksiyonlar ────────────────────────────────────────────────────

export function getVehicleDB(group: string): VehicleDB {
  switch (group) {
    case 'Otomobil':  return CAR_DB;
    case 'Motosiklet':return MOTORCYCLE_DB;
    case 'Ticari':    return COMMERCIAL_DB;
    case 'Karavan':   return CARAVAN_DB;
    case 'Bisiklet':  return BICYCLE_DB;
    default:          return CAR_DB;
  }
}

export function getBrandsFromDB(group: string): string[] {
  return Object.keys(getVehicleDB(group));
}

export function getModelsFromDB(group: string, brand: string): string[] {
  return Object.keys(getVehicleDB(group)[brand] ?? {});
}

export function getTrimsFromDB(group: string, brand: string, model: string): string[] {
  return getVehicleDB(group)[brand]?.[model] ?? [];
}
